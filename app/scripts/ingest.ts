/**
 * Ingest: NutriScan-Product-Database -> app catalog.
 *
 *   pnpm ingest
 *
 * Writes:
 *   shared/catalog/catalog.snapshot.json   scored products (bundled offline copy + DB seed source)
 *   assets/products/<id>.jpg               product images (folder structure of the source DB is untouched)
 *   lib/product-images.ts                  static require() map for React Native
 *   data/validation-report.md              data-quality warnings for the team
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { buildProduct } from "../shared/catalog/build";
import type { CatalogOverrides, CatalogProduct, CatalogSnapshot } from "../shared/catalog/types";
import { ALGORITHM_VERSION, RULE_SET_VERSION } from "../shared/nqss/engine";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dbRoot = resolve(appRoot, "..", "NutriScan-Product-Database", "Products");
const overridesPath = join(appRoot, "data", "catalog-overrides.json");

function listDirs(p: string): string[] {
  return readdirSync(p).filter((d) => statSync(join(p, d)).isDirectory()).sort();
}

const overrides: CatalogOverrides = existsSync(overridesPath)
  ? JSON.parse(readFileSync(overridesPath, "utf8"))
  : {};

const products: CatalogProduct[] = [];
/** Source photos vary (one is WebP named .jpg, one is 1792x2400). Phones get real JPEGs, max 800 px. */
const imageJobs: { from: string; to: string }[] = [];
const imagesDir = join(appRoot, "assets", "products");
mkdirSync(imagesDir, { recursive: true });

for (const kindDir of listDirs(dbRoot)) {
  for (const group of listDirs(join(dbRoot, kindDir))) {
    for (const productDir of listDirs(join(dbRoot, kindDir, group))) {
      const dir = join(dbRoot, kindDir, group, productDir);
      const detailsPath = join(dir, "details.json");
      if (!existsSync(detailsPath)) continue;
      const raw = JSON.parse(readFileSync(detailsPath, "utf8"));
      const image = readdirSync(dir).find((f) => /\.(jpe?g|png|webp)$/i.test(f)) ?? null;
      const draft = buildProduct(raw, { kindDir, group, imageKey: "", overrides });
      let id = draft.id;
      if (products.some((p) => p.id === id)) id = `${id}-${draft.barcode.slice(-4)}`;
      const product: CatalogProduct = { ...draft, id, imageKey: image ? id : "" };
      if (image) {
        imageJobs.push({ from: join(dir, image), to: join(imagesDir, `${id}.jpg`) });
        if (image !== "product.jpg") product.validation.push(`image_file_named_${image}`);
      } else product.validation.push("missing_image");
      products.push(product);
    }
  }
}

async function writeImages() {
  for (const job of imageJobs) {
    await sharp(job.from).rotate().resize(800, 800, { fit: "inside", withoutEnlargement: true }).flatten({ background: "#ffffff" }).jpeg({ quality: 80, mozjpeg: true }).toFile(job.to);
  }
}

// Duplicate barcodes would break scanning and USSD lookups.
const seen = new Map<string, string>();
for (const p of products) {
  const other = seen.get(p.barcode);
  if (other) p.validation.push(`duplicate_barcode_with_${other}`);
  seen.set(p.barcode, p.id);
}

const snapshot: CatalogSnapshot = {
  generatedAt: new Date().toISOString(),
  algorithmVersion: ALGORITHM_VERSION,
  ruleSetVersion: RULE_SET_VERSION,
  products,
};
writeFileSync(join(appRoot, "shared", "catalog", "catalog.snapshot.json"), `${JSON.stringify(snapshot, null, 1)}\n`);

const imageLines = products
  .filter((p) => p.imageKey)
  .map((p) => `  ${JSON.stringify(p.imageKey)}: require("../assets/products/${p.imageKey}.jpg"),`);
writeFileSync(
  join(appRoot, "lib", "product-images.ts"),
  `// Generated by scripts/ingest.ts - do not edit.\nimport type { ImageSourcePropType } from "react-native";\n\nexport const productImages: Record<string, ImageSourcePropType> = {\n${imageLines.join("\n")}\n};\n\nexport const placeholderImage: ImageSourcePropType = require("../assets/images/icon.png");\n`,
);

const flagged = products.filter((p) => p.validation.length > 0);
const scored = products.filter((p) => p.nqss?.score != null);
const report = [
  "# Catalog validation report",
  "",
  `Generated by \`pnpm ingest\`. Algorithm ${ALGORITHM_VERSION}, rule set ${RULE_SET_VERSION}.`,
  "",
  `- Products: ${products.length} (${products.filter((p) => p.kind === "food").length} food)`,
  `- Food products with a score: ${scored.length}`,
  `- Products with warnings: ${flagged.length}`,
  "",
  "Warnings never block scoring (teammate decision 1). Fix records in `data/catalog-overrides.json` after the showcase.",
  "",
  "| Product | Barcode | Score | Warnings |",
  "| --- | --- | ---: | --- |",
  ...flagged.map(
    (p) => `| ${p.name} | ${p.barcode} | ${p.nqss?.score ?? "-"} | ${p.validation.join(", ")} |`,
  ),
  "",
  "## All food scores",
  "",
  "| Product | Group | Score | Band | Free sugar method |",
  "| --- | --- | ---: | --- | --- |",
  ...scored
    .sort((a, b) => (b.nqss!.score ?? 0) - (a.nqss!.score ?? 0))
    .map(
      (p) =>
        `| ${p.name} | ${p.group} | ${p.nqss!.score} | ${p.nqss!.band} | ${p.nutrition?.values.free_sugar_g?.method ?? "declared"} |`,
    ),
  "",
].join("\n");
mkdirSync(join(appRoot, "data"), { recursive: true });
writeFileSync(join(appRoot, "data", "validation-report.md"), report);

writeImages()
  .then(() =>
    console.log(`Ingested ${products.length} products, ${scored.length} scored, ${flagged.length} with warnings.`),
  )
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
